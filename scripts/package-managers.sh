#!/usr/bin/env bash
# Write the Homebrew formula and Scoop manifest for a release into a tap
# checkout. Usage: scripts/package-managers.sh v0.2.0 dist/SHA256SUMS <tap-dir>
# Run by the release workflow after the archives are built; the formulas only
# point at the GitHub release assets and pin their SHA-256 sums.
set -euo pipefail
ver="${1:?version}"; sums="${2:?SHA256SUMS}"; tap="${3:?tap dir}"
v="${ver#v}"
base="https://github.com/veridit/muninn/releases/download/${ver}"
sha() { awk -v f="$1" '$2==f {print $1}' "$sums"; }
need() { [ -n "$(sha "$1")" ] || { echo "missing $1 in $sums" >&2; exit 1; }; }
for f in darwin_arm64.tar.gz darwin_amd64.tar.gz linux_arm64.tar.gz linux_amd64.tar.gz windows_amd64.zip windows_arm64.zip; do
  need "muninn_${v}_${f}"
done
mkdir -p "$tap/Formula" "$tap/bucket"

cat > "$tap/Formula/muninn.rb" <<EOF
# Generated by veridit/muninn scripts/package-managers.sh for ${ver}. Do not edit.
class Muninn < Formula
  desc "Local-first memory recall for AI coding agents (jcode, Claude Code, Codex, MCP)"
  homepage "https://github.com/veridit/muninn"
  version "${v}"
  license "MPL-2.0"

  on_macos do
    on_arm do
      url "${base}/muninn_${v}_darwin_arm64.tar.gz"
      sha256 "$(sha "muninn_${v}_darwin_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/muninn_${v}_darwin_amd64.tar.gz"
      sha256 "$(sha "muninn_${v}_darwin_amd64.tar.gz")"
    end
  end

  on_linux do
    on_arm do
      url "${base}/muninn_${v}_linux_arm64.tar.gz"
      sha256 "$(sha "muninn_${v}_linux_arm64.tar.gz")"
    end
    on_intel do
      url "${base}/muninn_${v}_linux_amd64.tar.gz"
      sha256 "$(sha "muninn_${v}_linux_amd64.tar.gz")"
    end
  end

  def install
    bin.install "muninn"
  end

  service do
    run [opt_bin/"muninn", "serve"]
    keep_alive true
    log_path var/"log/muninn.log"
    error_log_path var/"log/muninn.log"
  end

  def caveats
    <<~EOS
      Wire muninn into your agents (keeps backups, idempotent):
        muninn install all
      Keep the index fresh and the web UI on http://127.0.0.1:7431:
        brew services start muninn
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/muninn version")
  end
end
EOF

cat > "$tap/bucket/muninn.json" <<EOF
{
    "version": "${v}",
    "description": "Local-first memory recall for AI coding agents (jcode, Claude Code, Codex, MCP)",
    "homepage": "https://github.com/veridit/muninn",
    "license": "MPL-2.0",
    "architecture": {
        "64bit": {
            "url": "${base}/muninn_${v}_windows_amd64.zip",
            "hash": "$(sha "muninn_${v}_windows_amd64.zip")",
            "extract_dir": "muninn_${v}_windows_amd64"
        },
        "arm64": {
            "url": "${base}/muninn_${v}_windows_arm64.zip",
            "hash": "$(sha "muninn_${v}_windows_arm64.zip")",
            "extract_dir": "muninn_${v}_windows_arm64"
        }
    },
    "bin": "muninn.exe",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/veridit/muninn/releases/download/v\$version/muninn_\$version_windows_amd64.zip",
                "extract_dir": "muninn_\$version_windows_amd64"
            },
            "arm64": {
                "url": "https://github.com/veridit/muninn/releases/download/v\$version/muninn_\$version_windows_arm64.zip",
                "extract_dir": "muninn_\$version_windows_arm64"
            }
        },
        "hash": { "url": "https://github.com/veridit/muninn/releases/download/v\$version/SHA256SUMS" }
    }
}
EOF
echo "wrote $tap/Formula/muninn.rb and $tap/bucket/muninn.json for ${ver}"
